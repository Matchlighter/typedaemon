
import * as fs from "fs";
import * as path from "path";
import { TsConfigJson } from "type-fest";
import * as fse from 'fs-extra';

import { merger } from "@matchlighter/common_library/data/config";
import { Configuration } from "../hypervisor/config";
import { Hypervisor } from "../hypervisor/hypervisor";
import { TYPE_ALIASES } from "../hypervisor/vm";
import { TD_DEVELOPER_MODE, TYPEDAEMON_PATH, resolveSourceFile } from "./util";

const tsconfigMerger = merger<TsConfigJson>({
    // Concatenate, so user-provided `include`s extend (rather than replace) the ones we need
    include: (upper, lower) => [...upper || [], ...lower || []],
    compilerOptions: merger({
        paths: (upper, lower) => {
            const mrg = { ...upper }
            for (let [k, v] of Object.entries(lower)) {
                if (v[0] == '!') {
                    mrg[k] = v.slice(1);
                } else {
                    mrg[k] = [...v, ...upper[k] || []];
                }
            }
            return mrg;
        },
    }),
})

const EXPORTS_CONFIG_TYPE = /^\s*export\s+(?:(?:type|interface|class)\s+Config\b|(?:type\s+)?\{[^}]*\bConfig\b[^}]*\})/m;

async function appExportsConfigType(hv: Hypervisor, source: string) {
    const file = await resolveSourceFile(path.resolve(hv.working_directory, source));
    if (!file) return false;
    return EXPORTS_CONFIG_TYPE.test(await fs.promises.readFile(file, "utf8"));
}

/**
 * Generate a `.d.ts` that registers each configured app's config type in `AppRegistry`, so
 * `Configuration.apps[*].config` is type-checked. Types aren't analyzed here, only referenced.
 */
export async function generateAppRegistry(hv: Hypervisor) {
    const entries: string[] = [];
    // Keyed on the `source` as the user wrote it (`source` itself is rewritten to an absolute path during normalization)
    const sources = new Set(Object.values(hv.currentConfig.apps || {}).map(a => a?.declared_source).filter(Boolean));
    for (const source of sources) {
        const specifier = path.relative(hv.operations_directory, path.resolve(hv.working_directory, source))
            .split(path.sep).join("/")
            .replace(/\.[cm]?[jt]sx?$/, "");
        const mod = `import(${JSON.stringify(specifier)})`;
        // `export type`s aren't visible on `typeof import()`, so reference an explicit `Config` directly
        const config = await appExportsConfigType(hv, source) ? `; Config: ${mod}.Config` : "";
        const type = `{ module: typeof ${mod}${config} }`;
        entries.push(`        ${JSON.stringify(source)}: ${type};`);
    }
    return [
        "// Generated by TypeDaemon. Do not edit.",
        // Makes this file a module, so the `declare module` below augments rather than declares
        `export {};`,
        `declare module "@td" {`,
        `    interface AppRegistry {`,
        ...entries,
        `    }`,
        `}`,
        "",
    ].join("\n");
}

/**
 * Write a generated `.d.ts` (named `gen.<name>.d.ts`) into the operations directory, where the generated tsconfig picks it up.
 * Skips the write (and a TS server reload) if nothing changed.
 */
export async function saveGeneratedTypes(hv: Hypervisor, name: string, content: string) {
    const file = path.join(hv.operations_directory, `gen.${name}.d.ts`);
    const existing = await fs.promises.readFile(file, "utf8").catch((ex) => {
        if (ex.code == "ENOENT") return null;
        throw ex;
    });
    if (existing === content) return;
    await fse.mkdirp(hv.operations_directory);
    await fs.promises.writeFile(file, content);
}

export async function saveAppRegistry(hv: Hypervisor) {
    await saveGeneratedTypes(hv, "apps", await generateAppRegistry(hv));
}

export async function saveGeneratedTsconfig(hv: Hypervisor) {
    const typedaemon_dir = TD_DEVELOPER_MODE ? path.relative(hv.operations_directory, TYPEDAEMON_PATH) : "./node_modules/typedaemon/dist";
    const cfg = hv.currentConfig as Configuration;

    const paths = {}

    for (let [k, v] of Object.entries(TYPE_ALIASES)) {
        paths[k] = [v.replace("@TYPEDAEMON", typedaemon_dir).replace("@SYS_NODE_MODULES", "./node_modules")]
    }

    Object.assign(paths, {
        // "*": ["./node_modules/*"],
    })

    let tscfg: TsConfigJson = {
        "compilerOptions": {
            "allowSyntheticDefaultImports": false,
            "lib": [
                "es6",
                "dom",
                "es2017",
                "ES2020",
                "ESNext",
                "ES2022",
                "esnext.decorators",
            ] as any,
            // Bundler: extensionless imports + package.json `exports` resolution (apps are transformed by Babel, not tsc)
            "module": "ESNext",
            "moduleResolution": "Bundler",
            "sourceMap": true,
            "target": "ES2022",
            "esModuleInterop": true,
            "resolveJsonModule": true,
            "paths": paths,
        },
        "exclude": [
            "./source_environments",
            "./app_environments",
        ]
    }
    tscfg = tsconfigMerger.mergeConfigs(tscfg, { compilerOptions: { paths: cfg.path_maps || {} } }, cfg.tsconfig || {});
    await fse.mkdirp(hv.operations_directory);
    await fs.promises.writeFile(path.join(hv.operations_directory, "gen.tsconfig.json"), JSON.stringify(tscfg, null, 4));

}
